"""Issue #112: hand-over microkernels for Héctor's GEMM.

Writes, for each precision (fp32; f16f16f32 = FP16 A and B, FP32 C):
  xdsl_ukernels_<dt>.c / .h : our generated microkernels (static, our design, unchanged), each behind a
                              wrapper `xdsl_ukernel_<MR>x<NR>_<dt>` with Héctor's arguments
                              (GEMMLib_yolo b292c92, src/GEMM/gemm_blis.h: uk_intrinsic_fp32 / uk_intrinsic_fp16).
plus ref_ukernels.c / .h (naive reference: plain loops, same arguments), test_xdsl_ukernels.c (calls every
wrapper and the reference through his typedefs and compares them), a Makefile and a README, all into --out.

His semantics, kept by the wrapper: mr, nr, ldA, ldB unused (the full MR x NR tile is computed);
beta == 0 overwrites C, any other beta adds A*B to C (beta's value is not used); no alpha.
"""

import argparse
import os
import shutil
import subprocess
import sys

sys.path.append(os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

from xdsl.context import Context
from xdsl.dialects import arith, builtin, memref, scf
from xdsl.dialects import func as func_dialect
from xdsl.printer import Printer

from generate_pure_blis_project import merge_modules
from test_codeGeneration import BetaMode, build_gemm
from xdsltemplate.dialects.rvv import RVV
from xdsltemplate.transforms.arith_to_emitc import ArithToEmitCPass
from xdsltemplate.transforms.memref_load_to_emitc import MemrefLoadToEmitcPass
from xdsltemplate.transforms.memref_store_to_emitc import MemrefStoreToEmitcPass
from xdsltemplate.transforms.memref_to_emitc import MemRefToEmitCPass
from xdsltemplate.transforms.rvv_to_emitc import RVVToEmitCPass
from xdsltemplate.transforms.scf_to_emitc import SCFToEmitCPass

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_TRANSLATE = "/home/jlei/Documents/ws_MLIR/llvm_pj_dir_06092025/llvm-project/build/bin/mlir-translate"
VLEN_ELEMS = 8  # FP32 elements per m1 register at VLEN 256 (K1)

# dt -> C type of A and B
DTYPES = {"fp32": "float", "f16f16f32": "_Float16"}


def inner_name(dt, mr, nr, beta):
    return f"gemm_microkernel_v_{dt}_{mr}x{nr}_b{beta}"


def wrapper_name(dt, mr, nr):
    return f"xdsl_ukernel_{mr}x{nr}_{dt}"


def wrapper_proto(dt, mr, nr):
    t = DTYPES[dt]
    return (
        f"void {wrapper_name(dt, mr, nr)}(int mr, int nr, int kc, const {t} *Ar, const {t} *Br, "
        f"float *Cr, float beta, int ldA, int ldB, int Clda)"
    )


def lower_to_c(modules, translate, workdir, tag):
    ctx = Context()
    for d in (builtin.Builtin, func_dialect.Func, memref.MemRef, arith.Arith, scf.Scf, RVV):
        ctx.load_dialect(d)
    mod = merge_modules(*modules)
    for p in (MemRefToEmitCPass(), ArithToEmitCPass(), MemrefLoadToEmitcPass(),
              MemrefStoreToEmitcPass(), SCFToEmitCPass(), RVVToEmitCPass()):
        p.apply(ctx, mod)
    mlir_path = os.path.join(workdir, f"{tag}.mlir")
    c_path = os.path.join(workdir, f"{tag}.raw.c")
    with open(mlir_path, "w") as f:
        Printer(stream=f, print_generic_format=True).print_op(mod)
    subprocess.run([translate, "-allow-unregistered-dialect", "-mlir-to-cpp", mlir_path, "-o", c_path], check=True)
    with open(c_path) as f:
        return f.read()


def render_source(dt, tiles, kernel_code):
    # Our kernels stay internal: only the xdsl_ukernel_* wrappers are exported, so nothing clashes with his names.
    kernel_code = kernel_code.replace("void gemm_microkernel_v_", "static void gemm_microkernel_v_")
    assert "static static" not in kernel_code
    t = DTYPES[dt]
    out = [
        f"// Issue #112 hand-over: our xDSL-generated {dt} microkernels with Héctor's arguments.",
        "// Generated by tests/pure_xdsl_blis_rvv/gen_handover_ukernels.py. Do not edit.",
        f'#include "xdsl_ukernels_{dt}.h"',
        "#include <riscv_vector.h>",
        "",
        kernel_code,
        "",
    ]
    for mr, nr in tiles:
        out += [
            wrapper_proto(dt, mr, nr) + " {",
            "    float one = 1.0f;",
            "    (void)mr; (void)nr; (void)ldA; (void)ldB;",
            f"    if (beta == 0.0f) {inner_name(dt, mr, nr, 0)}(kc, &one, ({t} *)Ar, {mr}, ({t} *)Br, {nr}, &one, Cr, Clda);",
            f"    else              {inner_name(dt, mr, nr, 1)}(kc, &one, ({t} *)Ar, {mr}, ({t} *)Br, {nr}, &one, Cr, Clda);",
            "}",
            "",
        ]
    return "\n".join(out)


def render_header(dt, tiles):
    guard = f"XDSL_UKERNELS_{dt.upper()}_H"
    lines = [
        f"#ifndef {guard}",
        f"#define {guard}",
        "// Issue #112 hand-over. Arguments as Héctor's uk_intrinsic_fp32 / uk_intrinsic_fp16 (GEMMLib_yolo b292c92).",
        "// A: packed MR per k step; B: packed NR per k step; C column-major, Cr[j*Clda + i].",
        "// mr, nr, ldA, ldB are not used: the full MR x NR tile is always computed.",
        "// beta == 0: C = A*B. Any other beta: C += A*B (beta's value is not used). No alpha.",
        "// _Float16 is the same type as his fp16_t.",
        "#include <stddef.h>",
        '#ifdef __cplusplus\nextern "C" {\n#endif',
    ]
    lines += [wrapper_proto(dt, mr, nr) + ";" for mr, nr in tiles]
    lines += ["#ifdef __cplusplus\n}\n#endif", f"#endif // {guard}", ""]
    return "\n".join(lines)


def render_test(tiles):
    with open(os.path.join(HERE, "templates", "handover_test_ukernels.c")) as f:
        tpl = f.read()
    tables = []
    for dt in DTYPES:
        tables.append(f"static const struct entry_{dt} table_{dt}[] = {{")
        tables += [f"    {{{mr}, {nr}, {wrapper_name(dt, mr, nr)}}}," for mr, nr in tiles]
        tables.append("};")
    return tpl.replace("/*@TABLES@*/", "\n".join(tables))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", required=True, help="output folder (the hand-over bundle)")
    ap.add_argument("--mr", default="8,16,24,32", help="comma-separated MR values")
    ap.add_argument("--nr-max", type=int, default=16, help="NR runs 1..nr-max")
    ap.add_argument("--mlir-translate", default=DEFAULT_TRANSLATE)
    args = ap.parse_args()

    tiles = [(mr, nr) for mr in map(int, args.mr.split(",")) for nr in range(1, args.nr_max + 1)]
    os.makedirs(args.out, exist_ok=True)
    work = os.path.join(args.out, ".build")
    os.makedirs(work, exist_ok=True)

    for dt in DTYPES:
        mods = [
            build_gemm(mr=mr, nr=nr, vlen=VLEN_ELEMS, beta=beta, precision=dt, name=inner_name(dt, mr, nr, b))
            for mr, nr in tiles
            for b, beta in ((0, BetaMode.B0), (1, BetaMode.B1))
        ]
        code = lower_to_c(mods, args.mlir_translate, work, dt)
        with open(os.path.join(args.out, f"xdsl_ukernels_{dt}.c"), "w") as f:
            f.write(render_source(dt, tiles, code))
        with open(os.path.join(args.out, f"xdsl_ukernels_{dt}.h"), "w") as f:
            f.write(render_header(dt, tiles))
        print(f"[+] {dt}: {len(tiles)} kernels -> {args.out}/xdsl_ukernels_{dt}.c")

    with open(os.path.join(args.out, "test_xdsl_ukernels.c"), "w") as f:
        f.write(render_test(tiles))
    for src, dst in (("handover_Makefile", "Makefile"), ("handover_ref_ukernels.c", "ref_ukernels.c"),
                     ("handover_ref_ukernels.h", "ref_ukernels.h"), ("handover_README.md", "README.md")):
        shutil.copy(os.path.join(HERE, "templates", src), os.path.join(args.out, dst))
    shutil.rmtree(work)


if __name__ == "__main__":
    main()
