#!/usr/bin/env python3
"""Issue #55: write pack_only/scalar_pack.inc, the canonical scalar packers, from the generator.

The pack-only loop's `scalar` twin and its Bc check are `render_scalar_pack_functions`' own text,
not a hand copy. Run on the host (the generator needs xdsl); the series script does it before
copying pack_only/ to the board, the tests do it before building.

Usage: gen_scalar_inc.py [output path]   (default: scalar_pack.inc beside this file)
"""

import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from generate_pure_blis_project import render_scalar_pack_functions  # noqa: E402


def main(argv: list[str]) -> int:
    out = Path(argv[0]) if argv else HERE / "scalar_pack.inc"
    out.write_text("// generated by gen_scalar_inc.py from render_scalar_pack_functions; do not edit\n"
                   + render_scalar_pack_functions("float", "float"))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
